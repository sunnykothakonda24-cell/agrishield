export function translate(language, key, values = {}) {
  const aiChatKey = key.startsWith('aiChat.') ? key.slice(7) : null;
  const template = translations[language]?.[key] ||
    (aiChatKey ? aiChatTranslations[language]?.[aiChatKey] : undefined) ||
    translations.en[key] ||
    (aiChatKey ? aiChatTranslations.en?.[aiChatKey] : undefined) || key;
  return template.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}
